"""GAL-017: real pretrained Pythia-70M LoRA for CyberSand-like legal-action menus.

External synthetic host only. No game/runtime writes. This is an executable
*SLM* trainer, not a trained-model result. Without pinned pretrained weights,
Transformers and PEFT, --train fails explicitly; --self-test needs only stdlib.

Frozen DRIV3R synthetic host and observation/receipt semantics are imported
unmodified. The policy sees only radius-four material, bounded ledger and the
host's leased legal menu. Hidden corridor/goal/material arrays are never used
in model prompts, action rankings or teacher policy. Goal completion is read
solely for ex-post evaluation. Training/development/held-out seeds disjoint.

Attention: training labels come from a deterministic observation-limited oracle.
Action imitation is not artistic competence, and this source alone is not a
scientifically reproduced model or a native CyberSand contract validation.
"""
from __future__ import annotations
import argparse
import contextlib
import hashlib
import json
import random
import resource
import statistics
import time
from pathlib import Path

from frontier_memory import Ledger
from gal016_volatile_memory import BoundedLedger, PulseWorld
from lab import DECISION_CAP, START, sha
from material_corridors import visible_material
from route_scaffold import get_paint_candidates, route_actions

MODEL_ID = 'EleutherAI/pythia-70m-deduped'
MODEL_REVISION = 'e93a9faa9c77e5d09219f6c868bfc7a1bd65593c'
SCHEMA = 'gal-017-pythia70m-legal-menu/1'
ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
TRAIN_SEEDS = (3001001, 3001002, 3001003, 3001004, 3001005, 3001006)
DEV_SEEDS = (3005001, 3005002)
FINAL_SEEDS = (3009001, 3009002)
KINDS = ('path','tree','comb','deep_tree')
TARGETS = (48,64)
CAPACITIES = (81,161)
DYNAMICS = ('static','pulse')
assert not(set(TRAIN_SEEDS)&set(DEV_SEEDS)|set(TRAIN_SEEDS)&set(FINAL_SEEDS)|set(DEV_SEEDS)&set(FINAL_SEEDS))

def action_menu(offer, vocabulary):
    if vocabulary not in ('cell','swept'):
        raise ValueError('unknown action vocabulary')
    if not offer or 'STOP' not in offer:
        raise ValueError('host must offer STOP')
    menu = {name:path for name,path in offer.items()
            if vocabulary=='swept' or len(path)<=1}
    if not menu or len(menu)>len(ALPHABET):
        raise ValueError('legal catalog exceeds fixed 36-code capacity')
    assert set(menu)<=set(offer)
    return dict(sorted(menu.items()))

def oracle_choice(w,ledger,menu):
    """Observation-limited procedural teacher/control, NOT a neural model."""
    paints=get_paint_candidates(w,ledger,menu)
    if paints:
        return max(paints,key=lambda a:(len(a[1]),a[0]))[0]
    routes=route_actions(w,ledger,menu)
    if routes:
        return max(routes,key=lambda a:(len(a[1]),a[0]))[0]
    return 'STOP'

def descriptor(w,ledger,menu):
    """No hidden-geometry access. Contract: only observed crop, known ledger,
    public cursor/heading/task flags and leased host menu. No lease in text.
    """
    crop=visible_material(w,'material')
    x,y=w.cursor
    chars={0:'.',3:'#',5:'P',58:'I'}
    view='|'.join(''.join(chars.get(crop.get((x+dx,y+dy),-1),'?')
                          for dx in range(-4,5)) for dy in range(-4,5))
    # Historical material is never silently treated as current host truth.
    targets=len(ledger.targets())
    r=ledger.route(w.cursor)
    labels=[]
    for code,(name,path) in zip(ALPHABET,menu.items()):
        if path:
            dx=path[-1][0]-x;dy=path[-1][1]-y
        else:dx=dy=0
        labels.append(f'{code}={name}[{dx},{dy}]')
    return (f'Synthetic material worm. Task: paint traversable cells, START excluded. '
            f'Target={w.ink_target}; progress={w.decisions}; heading={w.heading}; '
            f'memory_known={len(ledger.known)}; frontier={targets}; route_len={len(r)}; '
            f'last3={",".join(t["action_id"] for t in w.trace[-3:]) or "none"}; '
            f'local_9x9={view}; legal: {" ".join(labels)}. Choice:')

def decision_state(w,ledger,vocabulary):
    offer,lease=w.offer()  # host leases are never generated by the model
    menu=action_menu(offer,vocabulary)
    prompt=descriptor(w,ledger,menu)
    return menu,lease,prompt

def make_world(seed,kind,target,capacity,dynamic,identity):
    return PulseWorld(seed,kind,'lift',f'gal017:{identity}:{seed}:{kind}:{target}:{dynamic}',target,dynamic),BoundedLedger(capacity)

def teacher_episode(seed,kind,target,capacity,dynamic,vocabulary,*,max_decisions=80):
    w,ledger=make_world(seed,kind,target,capacity,dynamic,'teacher-'+vocabulary)
    rows=[]
    while not w.stopped and w.decisions<min(DECISION_CAP,max_decisions) and w.goal-w.own:
        ledger.observe(w)
        menu,lease,prompt=decision_state(w,ledger,vocabulary)
        action=oracle_choice(w,ledger,menu)
        if action not in menu:
            raise AssertionError('oracle escaped offered menu')
        rows.append({'seed':seed,'kind':kind,'target':target,'capacity':capacity,
                     'dynamic':dynamic,'vocab':vocabulary,'prompt':prompt,
                     'menu':list(menu),'label':list(menu).index(action),
                     'observation_sha256':hashlib.sha256(prompt.encode()).hexdigest()})
        receipt=w.apply(action,lease,original_response=f'GAL017:oracle:{action}')
        ledger.accept(action,menu[action],receipt)
    return rows,{'complete':w.goal<=w.own,'decisions':w.decisions,
                 'coverage':len(w.own&w.goal)/target,'receipts_sha256':sha(w.trace),
                 'native_receipts':0,'resident_slm':0}

def task_grid(seeds,vocabulary):
    for seed in seeds:
        # Different pairings across world seeds; no hidden map is given to model.
        for kind in KINDS:
            for dynamic in DYNAMICS:
                yield seed,kind,48 if seed%2 else 64,81 if (seed+KINDS.index(kind))%2 else 161,dynamic,vocabulary

def collect(seeds,vocabulary,*,max_decisions):
    samples=[];episode_receipts=[]
    for t in task_grid(seeds,vocabulary):
        rows,result=teacher_episode(*t,max_decisions=max_decisions)
        samples.extend(rows)
        episode_receipts.append(dict(zip(('seed','kind','target','capacity','dynamic','vocab'),t),**result))
    return samples,episode_receipts

def synthetic_guard_tests():
    for vocabulary in ('cell','swept'):
        for dynamic in ('static','pulse'):
            w,ledger=make_world(3001001,'tree',48,81,dynamic,'selftest')
            for _ in range(20):
                ledger.observe(w)
                menu,lease,prompt=decision_state(w,ledger,vocabulary)
                host,_=w.offer()
                assert set(menu)<=set(host)
                assert len(menu)<=36 and len(prompt)<2400
                assert not any(len(p)>1 for p in menu.values()) if vocabulary=='cell' else True
                choice=oracle_choice(w,ledger,menu)
                before={q:w.material[w.idx(q)] for q in w.protected}
                receipt=w.apply(choice,lease,original_response='GAL017:selftest:'+choice)
                ledger.accept(choice,menu[choice],receipt)
                assert before=={q:w.material[w.idx(q)] for q in w.protected}
                assert all(q not in w.protected for q in w.own)
                if w.stopped:break
    # Cross-arm actual matched task, both sample and host receipts.
    cell,ce=teacher_episode(3001002,'path',48,161,'pulse','cell',max_decisions=25)
    swept,se=teacher_episode(3001002,'path',48,161,'pulse','swept',max_decisions=25)
    assert cell and swept
    assert all(len(row['menu'])<=36 for row in cell+swept)
    assert ce['native_receipts']==se['native_receipts']==0
    return {'self_test':'PASS','cell_teacher_examples':len(cell),
            'swept_teacher_examples':len(swept),
            'model_loaded':False,'trained_optimizer_updates':0}

def hashes(root):
    return {str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(root.rglob('*')) if p.is_file() and p.name!='SHA256SUMS.json'}

def load_slm():
    try:
        import torch
        from transformers import AutoModelForCausalLM,AutoTokenizer
        from peft import LoraConfig,get_peft_model
        from huggingface_hub import HfApi, cached_file
    except ImportError as ex:
        raise RuntimeError('BLOCKED: pinned pretrained Pythia-70M requires torch, transformers, peft, huggingface_hub and accessible base-model weights; no substitute model permitted') from ex
    info=HfApi().model_info(MODEL_ID,revision=MODEL_REVISION)
    if info.sha!=MODEL_REVISION:
        raise RuntimeError('model revision verification failed')
    torch.set_num_threads(2)
    tok=AutoTokenizer.from_pretrained(MODEL_ID,revision=MODEL_REVISION,trust_remote_code=False)
    if tok.pad_token is None:tok.pad_token=tok.eos_token
    # Pythia/GPT-NeoX uses one token for a subset of leading-space codes.
    ids=[]
    for c in ALPHABET:
        candidate=tok.encode(' '+c,add_special_tokens=False)
        if len(candidate)!=1:
            raise RuntimeError(f'action code {c!r} is not atomic for pinned tokenizer')
        ids.append(candidate[0])
    if len(set(ids))!=len(ids):raise RuntimeError('token code collision')
    base=AutoModelForCausalLM.from_pretrained(MODEL_ID,revision=MODEL_REVISION,
                            trust_remote_code=False,torch_dtype=torch.float32,use_safetensors=True)
    base.eval()
    # The revision is immutable; hash the actual downloaded tensor bytes too.
    tensor_file=cached_file(MODEL_ID,'model.safetensors',revision=MODEL_REVISION,local_files_only=True)
    if not tensor_file:raise RuntimeError('base model tensor provenance cannot be verified')
    base_sha=hashlib.sha256(Path(tensor_file).read_bytes()).hexdigest()
    model=get_peft_model(base,LoraConfig(r=4,lora_alpha=8,lora_dropout=0.0,
                     target_modules=['query_key_value'],task_type='CAUSAL_LM',bias='none'))
    return torch,tok,model,ids,base_sha

def slm_logits(torch,tok,model,ids,prompt,max_tokens=512,stock=False):
    tokens=tok(prompt,return_tensors='pt',truncation=True,max_length=max_tokens)
    # The host menu is at the end: fail closed if context truncates it.
    if len(tokens['input_ids'][0])>=max_tokens:
        raise RuntimeError('prompt truncated: unsafe action catalog')
    ctx=model.disable_adapter() if stock else contextlib.nullcontext()
    with ctx:
        out=model(**tokens).logits[0,-1]
    return out[torch.tensor(ids,device=out.device)]

def classify(torch,tok,model,code_ids,row,stock=False):
    t0=time.perf_counter()
    with torch.inference_mode():
        scores=slm_logits(torch,tok,model,code_ids,row['prompt'],stock=stock)
    legal=scores[:len(row['menu'])]
    choice=int(legal.argmax())
    return choice,(time.perf_counter()-t0)*1000

def train_slm(torch,tok,model,code_ids,train_rows,dev_rows,updates,lr):
    torch.manual_seed(17017);random.seed(17017)
    opt=torch.optim.AdamW((p for p in model.parameters() if p.requires_grad),lr=lr,weight_decay=0.01)
    assert sum(p.numel() for p in model.parameters() if p.requires_grad)>0
    model.train()
    history=[];rnd=random.Random(17017)
    for step in range(updates):
        row=train_rows[rnd.randrange(len(train_rows))]
        s=slm_logits(torch,tok,model,code_ids,row['prompt'])[:len(row['menu'])]
        loss=torch.nn.functional.cross_entropy(s.reshape(1,-1),torch.tensor([row['label']]))
        opt.zero_grad();loss.backward()
        torch.nn.utils.clip_grad_norm_((p for p in model.parameters() if p.requires_grad),1.0)
        opt.step()
        history.append({'update':step+1,'teacher_loss':round(float(loss.detach()),6)})
    model.eval()
    return history

def rollout_slm(torch,tok,model,code_ids,seed,kind,target,capacity,dynamic,vocabulary,
                *,stock=False,max_decisions=80):
    w,ledger=make_world(seed,kind,target,capacity,dynamic,'slm-stock' if stock else 'slm-adapted')
    decisions=[];latencies=[];unmasked_invalid=0;model_calls=0
    while not w.stopped and w.decisions<min(DECISION_CAP,max_decisions) and w.goal-w.own:
        ledger.observe(w)
        menu,token,prompt=decision_state(w,ledger,vocabulary)
        row={'menu':list(menu),'prompt':prompt}
        t0=time.perf_counter()
        with torch.inference_mode():scores=slm_logits(torch,tok,model,code_ids,prompt,stock=stock)
        latencies.append((time.perf_counter()-t0)*1000);model_calls+=1
        # Raw unmasked preference is diagnostic only; execution always legal.
        if int(scores.argmax())>=len(menu):unmasked_invalid+=1
        selected_index=int(scores[:len(menu)].argmax())
        name=list(menu)[selected_index]
        receipt=w.apply(name,token,original_response=f'GAL017:raw_code={ALPHABET[selected_index]};action={name};policy={"stock" if stock else "adapted"}')
        ledger.accept(name,menu[name],receipt)
        decisions.append({'action':name,'offered_sha256':token,'receipt_sha256':sha(receipt),
                          'prompt_sha256':hashlib.sha256(prompt.encode()).hexdigest()})
    assert not(w.own&w.protected)
    assert all(w.material[w.idx(p)]==w.original[w.idx(p)] for p in w.protected)
    return {'seed':seed,'kind':kind,'target':target,'capacity':capacity,'dynamic':dynamic,
           'vocabulary':vocabulary,'policy':'stock' if stock else 'adapted',
           'complete':bool(w.goal<=w.own),'coverage':round(len(w.own&w.goal)/target,6),
           'decisions':w.decisions,'ink':len(w.own),'model_calls':model_calls,
           'mean_inference_ms':round(statistics.mean(latencies),2) if latencies else 0.,
           'p95_inference_ms':round(sorted(latencies)[int(.95*(len(latencies)-1))],2) if latencies else 0.,
           'raw_unmasked_invalid':unmasked_invalid,'executed_illegal':0,
           'host_material_sha256':sha(w.material),'host_receipts_sha256':sha(w.trace),
           'trace':decisions,'native_receipts':0,'external_synthetic_only':True}

def main(argv=None):
    p=argparse.ArgumentParser()
    p.add_argument('--self-test',action='store_true')
    p.add_argument('--out',type=Path)
    p.add_argument('--updates',type=int,default=24)
    p.add_argument('--max-decisions',type=int,default=48)
    p.add_argument('--final-seeds',type=int,default=1,choices=(1,2))
    p.add_argument('--lr',type=float,default=0.00025)
    args=p.parse_args(argv)
    if args.self_test:
        print(json.dumps(synthetic_guard_tests(),indent=2));return
    if args.out is None or args.out.exists():p.error('--out must be a new directory')
    if not (1<=args.updates<=64 and 8<=args.max_decisions<=80 and 0<args.lr<=0.001):
        p.error('resource bounds exceeded')
    args.out.mkdir(parents=True,exist_ok=False)
    started=time.perf_counter()
    report={'schema':SCHEMA,'status':'STARTED','model':MODEL_ID,'revision':MODEL_REVISION,
            'training_seeds':TRAIN_SEEDS,'dev_seeds':DEV_SEEDS,'final_seeds':FINAL_SEEDS,
            'max_decisions':args.max_decisions,'optimizer_updates_requested':args.updates,
            'final_seeds_consumed':FINAL_SEEDS[:args.final_seeds],
            'source_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'host_fixture_sha256':{p.name:hashlib.sha256((Path(__file__).parent/p).read_bytes()).hexdigest()
                    for p in map(Path,('lab.py','material_corridors.py','frontier_memory.py',
                                  'route_scaffold.py','gal016_volatile_memory.py'))},
            'synthetic_only':True,'native_receipts':0,'game_writes':0}
    try:
        torch,tok,model,code_ids,model_sha=load_slm()
        report['base_model_weights_sha256']=model_sha
        # Real training: train two LoRA variants with distinct candidate languages.
        for vocab in ('cell','swept'):
            train_rows,train_ctrl=collect(TRAIN_SEEDS,vocab,max_decisions=args.max_decisions)
            dev_rows,dev_ctrl=collect(DEV_SEEDS,vocab,max_decisions=args.max_decisions)
            if not train_rows or not dev_rows:raise RuntimeError('no training examples')
            report[vocab]={'n_train':len(train_rows),'n_dev':len(dev_rows),
                           'train_prompt_sha256':sha([r['observation_sha256'] for r in train_rows]),
                           'dev_prompt_sha256':sha([r['observation_sha256'] for r in dev_rows]),
                           'teacher_rollouts':train_ctrl+dev_ctrl}
            initial=[classify(torch,tok,model,code_ids,r,stock=True)[0]==r['label'] for r in dev_rows[:24]]
            # Fresh adapter for each vocabulary; don't allow carryover across arms.
            if vocab=='swept':
                torch,tok,model,code_ids,other_sha=load_slm()
                if other_sha!=model_sha:raise RuntimeError('base model bytes changed between arms')
            history=train_slm(torch,tok,model,code_ids,train_rows,dev_rows,args.updates,args.lr)
            report[vocab]['dev24_stock_accuracy']=sum(initial)/len(initial)
            report[vocab]['training_history']=history
            target_dir=args.out/vocab
            target_dir.mkdir(parents=True,exist_ok=False)
            model.save_pretrained(target_dir/'adapter',safe_serialization=True)
            # Reserve FINAL for the first and only evaluation pass.
            final=[]
            for task in task_grid(FINAL_SEEDS[:args.final_seeds],vocab):
                for stock in (True,False):
                    final.append(rollout_slm(torch,tok,model,code_ids,*task,
                                            stock=stock,max_decisions=args.max_decisions))
            (target_dir/'closed_loop.json').write_text(json.dumps(final,indent=2,sort_keys=True)+'\n')
            report[vocab]['heldout']={policy:{'n':len(q),
                'completed':sum(r['complete'] for r in q),
                'mean_coverage':round(statistics.mean(r['coverage'] for r in q),4),
                'mean_model_calls':round(statistics.mean(r['model_calls'] for r in q),2),
                'mean_inference_ms':round(statistics.mean(r['mean_inference_ms'] for r in q),2),
                'raw_unmasked_invalid':sum(r['raw_unmasked_invalid'] for r in q),
                'executed_illegal':sum(r['executed_illegal'] for r in q)}
                for policy in ('stock','adapted') for q in [[r for r in final if r['policy']==policy]]}
        report['status']='COMPLETED'
    except Exception as e:
        report['status']='BLOCKED_OR_FAILED';report['error']=repr(e)
        raise
    finally:
        report['wall_seconds']=round(time.perf_counter()-started,2)
        report['peak_rss_kib']=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        (args.out/'report.json').write_text(json.dumps(report,sort_keys=True,indent=2)+'\n')
        (args.out/'SHA256SUMS.json').write_text(json.dumps(hashes(args.out),sort_keys=True,indent=2)+'\n')
        print(json.dumps({'status':report['status'],'report':str(args.out/'report.json')},indent=2))

if __name__=='__main__':main()
