"""D021: bounded DAgger-style distribution-shift repair for a compact standalone policy.

On-policy states are generated by the *compact student*, then labelled by the
frozen synthetic D017 controller (D007 backbone + D017 branch gate). The parent
Q8 receipts establish a source-pinned style prior, NOT original parent actions
on these generated states. All game worlds are external/synthetic. No game ABI
or production defaults are modified; checkpoints remain outside Git history.
"""
from __future__ import annotations
import argparse, collections
from pathlib import Path
import numpy as np
from .lab import ACTIONS, STYLES, Game, feats
from .repair import adverse, load
from .source_parent_branch_gate import Controller, Gate, parents, sha, js
from .branch_retention_020 import CASES, fit, rollout, summary, bootstrap, admissibility

SCHEMA='driv3r.distill.d021-onpolicy-correction/1'
TRAIN=range(61001,61025)
VALID=range(62001,62009)
TEST=range(63001,63017)
CONFIRM=range(64001,64017)
D007='1a4a35f8f15f979b8460121d31021d562a457de78d86de9b9d2fedbcec05e38f'
D017='715dff35c08a4d19bb7f523925eace020f35bdcaa3bc7bfe44bf2aa67606f11f'
Q8='140342c16a0b8c6c8d2c3bc6071767885b15096d5a53bbf304979f3015c86522'

def check_splits():
 groups=[set(v) for v in (TRAIN, VALID, TEST, CONFIRM)]
 if any(groups[i]&groups[j] for i in range(4) for j in range(i+1,4)):
  raise AssertionError('split overlaps')
 if any(len(x)!=n for x,n in zip(groups,(24,8,16,16))):raise AssertionError('split cardinality')

def collect(student, teacher):
 """Produce student-state teacher labels; never use validation/test states."""
 rows=[];stats=collections.Counter()
 for seed in TRAIN:
  for style in STYLES:
   for case in CASES:
    g=Game(seed,style)
    for tick in range(80):
     adverse(g,case);o=g.obs();x=feats(o)
     sa=student.predict(o);ta=teacher.predict(o)
     legal=np.asarray([a in o['legal'] for a in ACTIONS],dtype=np.uint8)
     if sa not in o['legal'] or ta not in o['legal']:raise AssertionError('illegal action')
     scores=teacher.base.scores(x).copy()
     scores[3]+=teacher.bonus_for(o)
     scores=np.where(legal>0,scores,-1e5)
     rows.append((x.astype('float32'),scores.astype('float32'),legal,
                  ACTIONS.index(ta),sa!=ta))
     stats[('mismatch' if sa!=ta else 'match',case)]+=1
     g.step(sa)
     if g.stopped:break
 if not rows:raise ValueError('empty on-policy corpus')
 x,t,m,y,d=(np.asarray([r[i] for r in rows]) for i in range(5))
 if x.shape[1]!=100 or t.shape[1]!=6:raise ValueError('feature shape')
 if not m[np.arange(len(y)),y].all():raise AssertionError('illegal teacher labels')
 return ({'x':x,'t':t,'m':m,'y':y,'d':d.astype('bool')},
         {f'{label}/{case}':int(v) for (label,case),v in sorted(stats.items())})

def combine(offline,onpolicy,disagreement_weight,all_weight):
 """Fixed ratios; discrepancies are on-policy only and cannot peek at test."""
 if not 0<=disagreement_weight<=8 or not 0<=all_weight<=8:
  raise ValueError('replication limit')
 data={}
 ids=np.flatnonzero(onpolicy['d'])
 for k in ('x','t','m','y'):
  chunks=[offline[k]]
  if all_weight:chunks += [onpolicy[k]]*all_weight
  if disagreement_weight and len(ids):chunks += [onpolicy[k][ids]]*disagreement_weight
  data[k]=np.concatenate(chunks)
 return data

def jsonl(path,rows):Path(path).write_text(''.join(js(r)+'\n' for r in rows))

def main(argv=None):
 ap=argparse.ArgumentParser()
 for key in ('d007','d017','q8','d020','offline'):
  ap.add_argument('--'+key,type=Path,required=True)
 ap.add_argument('--out',type=Path,required=True)
 ap.add_argument('--steps',type=int,default=120)
 a=ap.parse_args(argv)
 check_splits()
 if not 1<=a.steps<=200:raise ValueError('bounded per-candidate budget max 200')
 source_hashes={k:sha(getattr(a,k)) for k in ('d007','d017','q8','d020','offline')}
 for key,expected in [('d007',D007),('d017',D017),('q8',Q8)]:
  if source_hashes[key]!=expected:raise ValueError('source SHA mismatch: '+key)
 with np.load(a.offline,allow_pickle=False) as z:
  offline={k:z[k] for k in ('x','t','m','y')}
 if offline['x'].shape[1]!=100 or len(offline['x'])<1000:raise ValueError('offline corpus invalid')
 for k,v in offline.items():
  if not np.isfinite(v).all():raise AssertionError('nonfinite offline '+k)
 if not offline['m'][np.arange(len(offline['y'])),offline['y']].all():
  raise AssertionError('illegal offline teacher target')
 parent=load(a.d007)
 teacher=Controller(parent,parents(a.q8),Gate.read(a.d017),.5,.58)
 initial=load(a.d020)
 if initial.w1.shape!=(100,44):raise ValueError('unexpected compact student shape')
 onpolicy,counts=collect(initial,teacher)
 out=a.out;out.mkdir(parents=True,exist_ok=True)
 np.savez_compressed(out/'d021_onpolicy_corpus.npz',**onpolicy)
 recipes=[('d021_mild',1,1,.10),('d021_strong',1,5,.20)]
 variants={};validations={};updated=0
 for idx,(name,all_w,dis_w,strength) in enumerate(recipes):
  ds=combine(offline,onpolicy,dis_w,all_w)
  obj=load(a.d020)
  info=fit(obj,ds,a.steps,211001+idx,strength,anchor_strength=.055,lr=.0008)
  updated+=info['updates']
  obj.save(out/(name+'.npz'));variants[name]=obj
  val,_,_=rollout(VALID,{'d017':teacher,name:obj})
  validations[name]={'guard':admissibility(summary(val),name),
    'fit':info,'corpus_rows':int(len(ds['y'])),'source_sha256':sha(out/(name+'.npz'))}
 eligible=[n for n,r in validations.items() if r['guard']['admissible']]
 selected=max(eligible or variants,key=lambda n:validations[n]['guard']['score'])
 controls={'d017':teacher,'d020':load(a.d020),'d021_mild':variants['d021_mild'],
           'd021_strong':variants['d021_strong']}
 test,actions,_=rollout(TEST,controls,draw=out/'pngs',receipt_seeds=[63001,63005,63009,63013])
 confirm,_,_=rollout(CONFIRM,controls)
 jsonl(out/'d021_test.jsonl',test);jsonl(out/'d021_confirmation.jsonl',confirm)
 jsonl(out/'d021_actions.jsonl',actions)
 result={'schema':SCHEMA,'environment':'external_synthetic_host','native_game_executed':False,
  'parent_inference_on_new_game_states':False,'source_q8_seed':570,
  'source_sha256':source_hashes,'onpolicy_sha256':sha(out/'d021_onpolicy_corpus.npz'),
  'new_onpolicy_observations':len(onpolicy['y']),
  'student_teacher_disagreement_count':int(onpolicy['d'].sum()),
  'onpolicy_by_condition':counts,'offline_observations':len(offline['y']),
  'splits':{'train':[TRAIN.start,TRAIN.stop-1],'validation':[VALID.start,VALID.stop-1],
            'test':[TEST.start,TEST.stop-1],'confirmation':[CONFIRM.start,CONFIRM.stop-1]},
  'candidate_validation':validations,'optimizer_updates':updated,
  'selected_diagnostic':selected,'validation_eligible':eligible,
  'test':summary(test),'confirmation':summary(confirm),
  'test_ci':bootstrap(test,selected,TEST),'confirmation_ci':bootstrap(confirm,selected,CONFIRM),
  'test_guard':admissibility(summary(test),selected),
  'confirmation_guard':admissibility(summary(confirm),selected)}
 # The third split is explicitly an exploratory, post-hoc fresh-seed diagnostic,
 # added after viewing first test/confirmation. Never use it for candidate choice.
 third,_actions,_=rollout(range(65001,65017),controls)
 jsonl(out/'d021_third_untouched.jsonl',third)
 result['posthoc_third_seeds']=[65001,65016]
 result['posthoc_third']=summary(third)
 result['posthoc_third_guard']=admissibility(summary(third),selected)
 result['posthoc_third_ci']=bootstrap(third,selected,range(65001,65017))
 result['promotion']=('RESEARCH_CANDIDATE_unvalidated_native' if eligible
    and result['test_guard']['admissible'] and result['confirmation_guard']['admissible']
    else 'REJECTED_closed_loop_failure')
 (out/'d021_metrics.json').write_text(js(result)+'\n')
 (out/'SHA256SUMS.txt').write_text(''.join(
  f'{sha(p)}  {p.relative_to(out)}\n' for p in sorted(out.rglob('*'))
  if p.is_file() and p.name!='SHA256SUMS.txt'))
 print(js({'selected':selected,'promotion':result['promotion'],
           'train':{'n':len(onpolicy['y']),'disagreement':int(onpolicy['d'].sum())},
           'validation':validations,'test_guard':result['test_guard'],
           'confirmation_guard':result['confirmation_guard']}),flush=True)
 return result

if __name__=='__main__':main()
